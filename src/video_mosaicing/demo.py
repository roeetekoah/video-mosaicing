"""Self-contained generated demo; no external footage or camera calibration needed."""
import argparse
from pathlib import Path

import cv2

from .io import save_result
from .pipeline import build_mosaic
from .scene import camera_sequence
from .synthetic import calibrated_sequence


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=Path('demo-output/generated'))
    args=parser.parse_args(argv)
    if args.output.exists() and any(args.output.iterdir()): parser.error("Output directory must be empty")
    cv2.setNumThreads(1);cv2.setRNGSeed(47)
    _,frames,_=camera_sequence()
    for name,sequence in [('harbor',frames),('tilted-pan',calibrated_sequence(seed=701,kind='tilted_pan').frames)]:
        result=build_mosaic(enumerate(sequence))
        result.evidence['input_origin']='procedurally generated by video_mosaicing.demo'
        save_result(result,args.output/name)
        print(name,result.image.shape,len(result.evidence['selected_source_indices']),'selected frames')
    return 0


if __name__=='__main__': main()
